import { createHash, createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url)));
const keyText = process.env.BETTERWX_UPDATE_PRIVATE_KEY;
if (!keyText) throw new Error('BETTERWX_UPDATE_PRIVATE_KEY is required; refusing unsigned release.');
const key = createPrivateKey(keyText);
const trusted = readFileSync(new URL('../desktop/update-public-key.txt', import.meta.url), 'utf8').trim();
const actual = createPublicKey(key).export({ type: 'spki', format: 'der' }).subarray(-32).toString('base64');
if (trusted !== actual) throw new Error('Release private key does not match the public key embedded in the app.');
if (process.env.GITHUB_REF_TYPE === 'tag' && process.env.GITHUB_REF_NAME !== `v${pkg.version}`) throw new Error('Tag must match package version.');
const repository = process.env.GITHUB_REPOSITORY || 'shusfun/BetterWX';
if (repository !== 'shusfun/BetterWX') throw new Error('Update repository must match desktop configuration.');
const file = resolve(process.argv[2] || 'release/BetterWX.exe');
const bytes = readFileSync(file);
const notes = process.env.RELEASE_NOTES || `BetterWX ${pkg.version}`;
const manifest = JSON.stringify({ version: pkg.version, notes, target: 'windows-x86_64', url: `https://github.com/${repository}/releases/download/v${pkg.version}/BetterWX.exe`, size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') }, null, 2) + '\n';
const signature = sign(null, Buffer.from(manifest), key);
if (!verify(null, Buffer.from(manifest), createPublicKey(key), signature)) throw new Error('Signature verification failed.');
mkdirSync('release', { recursive: true });
writeFileSync('release/update.json', manifest);
writeFileSync('release/update.json.sig', signature.toString('base64') + '\n');
console.log(`Signed release manifest for ${pkg.version}`);
